/**
 * Centre of the build plate, read from the printer's own printable_area rather
 * than assumed. The A1 mini is 180 mm, not 256, so a hardcoded centre would
 * place every part off the plate.
 */
function plateCentre(config: ProjectConfig): { x: number; y: number } {
  const area = config.printable_area;
  if (Array.isArray(area) && area.length) {
    let maxX = 0;
    let maxY = 0;
    for (const corner of area) {
      const [x, y] = String(corner).split("x").map(Number);
      if (Number.isFinite(x) && x > maxX) maxX = x;
      if (Number.isFinite(y) && y > maxY) maxY = y;
    }
    if (maxX > 0 && maxY > 0) return { x: maxX / 2, y: maxY / 2 };
  }
  // Every supported printer publishes printable_area; this is a last resort.
  return { x: 128, y: 128 };
}

/**
 * The Application metadata string in 3dmodel.model MUST look like
 * "BambuStudio-<version>".
 *
 * Bambu Studio parses a version out of this field and dereferences the result
 * without checking it. Writing an honest producer name such as "CaseFoundry"
 * makes the slicer segfault (exit 139) the moment the project is opened, with
 * no error message. Verified by bisection: swapping only this one file into a
 * known-good project reproduced the crash, and changing only this one string
 * fixed it.
 *
 * The real producer is recorded in the Origin field instead, so provenance is
 * kept without tripping the parser.
 */
const BAMBU_APPLICATION_TAG = "BambuStudio-02.08.01.55";

