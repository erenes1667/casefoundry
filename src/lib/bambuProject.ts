/**
 * Writes a genuine Bambu Studio project file.
 *
 * CaseFoundry 2026.8.0 exported with @jscad/3mf-serializer, which emits a bare
 * mesh-only 3MF. Bambu Studio then opened it with generic defaults, so every
 * tuned print parameter the app displayed was silently discarded on the way
 * out. This module instead emits the full project: a complete
 * project_settings.config, per-object model_settings.config, and the OPC
 * relationship graph Bambu expects.
 *
 * The 572-key base config is lifted verbatim from a print-verified P2S project
 * (src/data/bambu-p2s-04-base.json) rather than assembled from guesses. Only
 * the keys we genuinely know how to set are overridden.
 */

type ConfigValue = string | string[] | number | boolean | null;
type ProjectConfig = Record<string, ConfigValue>;

